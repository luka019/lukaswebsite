const titleByLanguage = {
  ka: "Luka / Law — ტექნოლოგიური და ციფრული სამართალი",
  en: "Luka / Law — Technology & Digital Law"
};

let currentLanguage = "ka";
const languageButton = document.querySelector("[data-language-toggle]");
const mobileMenu = document.querySelector("#mobile-menu");
const menuButton = document.querySelector(".menu-toggle");

function applyLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.title = titleByLanguage[language];
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translations[language][element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  if (languageButton) {
    languageButton.textContent = language === "ka" ? "EN" : "KA";
    languageButton.setAttribute("aria-label", language === "ka" ? "Switch to English" : "ქართულზე გადართვა");
  }
  try {
    window.localStorage.setItem("luka-law-language", language);
  } catch (error) {
    // Language switching remains available when browser storage is blocked.
  }
}

languageButton?.addEventListener("click", () => {
  applyLanguage(currentLanguage === "ka" ? "en" : "ka");
});

menuButton?.addEventListener("click", () => {
  const isOpen = mobileMenu.classList.toggle("is-open");
  menuButton.setAttribute("aria-expanded", String(isOpen));
  menuButton.setAttribute("aria-label", isOpen ? "მენიუს დახურვა" : "მენიუს გახსნა");
});

mobileMenu?.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", () => {
    mobileMenu.classList.remove("is-open");
    menuButton?.setAttribute("aria-expanded", "false");
  });
});

const year = document.querySelector("#year");
if (year) year.textContent = new Date().getFullYear();

let savedLanguage = null;
try {
  savedLanguage = window.localStorage.getItem("luka-law-language");
} catch (error) {
  savedLanguage = null;
}
if (savedLanguage === "en") applyLanguage("en");
